"""Compile editable ASCII maps and PNG sprites into program-memory C++ assets."""

import argparse
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
TILES = {".": 0, "#": 1, "~": 2, "D": 3, "=": 4}


def read_sprite_sheet(name, columns, rows):
    path = ROOT / "assets_src" / name
    with Image.open(path) as image:
        if image.format != "PNG" or image.size != (columns * 8, rows * 8):
            raise ValueError(f"{path}: expected a {columns * 8}x{rows * 8} PNG")
        pixels = image.convert("RGBA")
        if any(pixel not in ((0, 0, 0, 255), (255, 255, 255, 255)) for pixel in pixels.getdata()):
            raise ValueError(f"{path}: use opaque black and white pixels only")

    return [
        [
            "".join(
                "#" if pixels.getpixel((frame_x * 8 + x, frame_y * 8 + y))[0] else "."
                for x in range(8)
            )
            for y in range(8)
        ]
        for frame_y in range(rows)
        for frame_x in range(columns)
    ]


def frame_bytes(rows):
    return [sum(1 << y for y in range(8) if rows[y][x] == "#") for x in range(8)]


def array_lines(declaration, values, row_width=16):
    lines = [f"{declaration} = {{"]
    for start in range(0, len(values), row_width):
        lines.append("    " + ", ".join(map(str, values[start : start + row_width])) + ",")
    lines.append("};")
    return lines


def sprite_lines(name, frames, mask=None):
    lines = [f"constexpr uint8_t PROGMEM {name}[] = {{", "    8, 8, // width, height"]
    for frame_index, rows in enumerate(frames):
        assert len(rows) == 8 and all(len(row) == 8 for row in rows)
        pixels = frame_bytes(rows)
        if mask is not None:
            pixels = [byte for pair in zip(pixels, mask) for byte in pair]
        lines.extend(["", f"    // Frame {frame_index}"])
        lines.extend(f"    // {row}" for row in rows)
        lines.append("    " + ", ".join(f"0x{byte:02x}" for byte in pixels) + ",")
    lines.append("};")
    return lines


def generate():
    parts = [
        "/* Generated by tools/generate_assets.py; edit assets_src instead. */",
        "// clang-format off: preserve authored tile rows and data records.",
    ]
    for name, symbol in [("outdoor", "FIELD"), ("interior", "ROOM")]:
        rows = (ROOT / "assets_src" / f"{name}.txt").read_text().splitlines()
        width = len(rows[0])
        assert all(len(row) == width for row in rows), f"{name}: uneven rows"
        assert 16 <= width <= 255 and 8 <= len(rows) <= 255
        assert sum(row.count("D") for row in rows) == 1, "one paired doorway per area"
        data = [TILES[c] for row in rows for c in row]
        parts += array_lines(f"static constexpr uint8_t PROGMEM {symbol}_TILES[]", data, width)
        parts.append(
            f"static constexpr Area PROGMEM {symbol}_AREA = {{{width}, {len(rows)}, {symbol}_TILES}};"
        )
        parts.append("")
    # Stable identities: Iona=1 in interior; outdoor actors never roam over its exit.
    definitions = [
        (48, 32, 48, 32, 48, 32, 1, 0),
        (48, 80, 24, 64, 72, 104, 2, 1),
        (144, 32, 136, 16, 176, 56, 3, 1),
        (184, 96, 176, 80, 224, 128, 4, 1),
    ]
    definitions += [
        (24 + i * 24, 136, 16 + i * 24, 128, 32 + i * 24, 144, 5 + i, 1) for i in range(9)
    ]
    parts.append("static constexpr NpcDef PROGMEM NPC_DEFS[] = {")
    parts.extend("    {" + ", ".join(map(str, definition)) + "}," for definition in definitions)
    parts.append("};")
    parts.append("// clang-format on")
    world = "\n".join(parts) + "\n"
    tile_frames = read_sprite_sheet("tiles.png", 5, 1)
    actor_frames = read_sprite_sheet("actors.png", 2, 4)
    # Clear the silhouette behind each actor, including black facial pixels.
    actor_mask = frame_bytes(read_sprite_sheet("actor_mask.png", 1, 1)[0])
    art = [
        "/* Generated; eight actor frames, interleaved plus masks. */",
        '#include "rpg.h"',
        "",
        "// clang-format off: preserve frame artwork and byte groups.",
    ]
    art += sprite_lines("TILE_SPRITES", tile_frames)
    art.append("")
    art += sprite_lines("ACTOR_SPRITES", actor_frames, actor_mask)
    art.append("// clang-format on")
    return {"world_assets.h": world, "sprites.cpp": "\n".join(art) + "\n"}


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    target = ROOT / "generated"
    target.mkdir(exist_ok=True)
    for name, text in generate().items():
        path = target / name
        if args.check:
            assert path.read_text() == text, f"{path} is stale; regenerate assets"
        else:
            path.write_text(text, encoding="utf-8", newline="\n")
    print("Asset generation/check passed (stable IDs, map shapes, sprite layouts).")


if __name__ == "__main__":
    main()
