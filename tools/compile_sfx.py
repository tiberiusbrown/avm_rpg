"""Compile every AVMS sound effect and generate the effect IDs and playback table."""

import argparse
from pathlib import Path
import re
import runpy


def write_if_changed(path, text):
    if not path.exists() or path.read_text(encoding="utf-8") != text:
        path.write_text(text, encoding="utf-8", newline="\n")


def generate(compiler_path, source_dir, output_dir):
    scores = sorted(source_dir.glob("*.avms"))
    if not 1 <= len(scores) <= 255:
        raise ValueError("sound effect catalog requires between 1 and 255 AVMS scores")
    compiler = runpy.run_path(str(compiler_path))

    banner = "// Generated by tools/compile_sfx.py; do not edit.\n#pragma once\n"
    symbols = {"SFX_COUNT"}
    effects = []
    data = banner
    for score in scores:
        symbol = "SFX_" + re.sub(r"[^A-Za-z0-9_]", "_", score.stem).upper()
        if symbol in symbols:
            raise ValueError(f"{score.name}: duplicate or reserved effect identifier {symbol}")
        symbols.add(symbol)
        effects.append(symbol)
        stream = compiler["compile_source"](score.read_text(encoding="utf-8"), score)
        array = compiler["c_array"](stream, symbol + "_DATA")
        data += "\n" + array.replace("static const ", "static constexpr ", 1)

    ids = banner + "#include <stdint.h>\n\nenum SFX : uint8_t {\n"
    ids += "".join(f"    {symbol},\n" for symbol in effects)
    ids += "    SFX_COUNT\n};\n"

    data += "\nconstexpr SfxTrack AVM_PROGMEM SFX_TRACKS[] = {\n"
    data += "".join(f"    {{{symbol}_DATA}},\n" for symbol in effects)
    data += "};\n"

    output_dir.mkdir(parents=True, exist_ok=True)
    write_if_changed(output_dir / "sfx_ids.h", ids)
    write_if_changed(output_dir / "sfx_data.h", data)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--compiler", type=Path, required=True)
    parser.add_argument("--source-dir", type=Path, required=True)
    parser.add_argument("--output-dir", type=Path, required=True)
    args = parser.parse_args()
    generate(args.compiler, args.source_dir, args.output_dir)
