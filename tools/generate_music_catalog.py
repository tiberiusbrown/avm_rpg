"""Generate the song IDs and playback list from the editable AVMS scores."""

import argparse
import ast
import json
from pathlib import Path
import re


def song_title(score):
    tokens = re.findall(r'//[^\n]*|"(?:\\.|[^"\\])*"|[A-Za-z_]\w*',
                        score.read_text(encoding="utf-8"))
    for index, token in enumerate(tokens):
        if token in ("instrument", "envelope", "phrase", "effect", "channel"):
            break
        if token == "title":
            return ast.literal_eval(tokens[index + 1])
    return score.stem.replace("_", " ").replace("-", " ").title()


def write_if_changed(path, text):
    if not path.exists() or path.read_text(encoding="utf-8") != text:
        path.write_text(text, encoding="utf-8", newline="\n")


def generate(source_dir, output_dir):
    scores = sorted(source_dir.glob("*.avms"))
    if not 1 <= len(scores) <= 255:
        raise ValueError("music catalog requires between 1 and 255 AVMS scores")

    songs = []
    symbols = {"MUSIC_COUNT", "MUSIC_DEFAULT"}
    for score in scores:
        symbol = "MUSIC_" + re.sub(r"[^A-Za-z0-9_]", "_", score.stem).upper()
        if symbol in symbols:
            raise ValueError(f"{score.name}: duplicate or reserved song identifier {symbol}")
        if any(character in score.name for character in ('"', "\\", "\n", "\r")):
            raise ValueError(f"{score.name}: filename cannot be used in a C++ include")
        symbols.add(symbol)
        songs.append((score, symbol, song_title(score)))

    default = next((symbol for score, symbol, _ in songs if score.stem == "test"), songs[0][1])
    banner = "// Generated by tools/generate_music_catalog.py; do not edit.\n#pragma once\n"
    catalog = banner + "#include <stdint.h>\n\nenum MUSIC_TRACK : uint8_t {\n"
    catalog += "".join(f"    {symbol},\n" for _, symbol, _ in songs)
    catalog += f"    MUSIC_COUNT,\n    MUSIC_DEFAULT = {default}\n}};\n"

    tracks = banner + "".join(f'#include "{score.stem}_music.h"\n' for score, _, _ in songs)
    tracks += "\n"
    tracks += "".join(f"constexpr char AVM_PROGMEM {symbol}_TITLE[] = {json.dumps(title, ensure_ascii=False)};\n"
                      for _, symbol, title in songs)
    tracks += "\nconstexpr MusicTrack AVM_PROGMEM MUSIC_TRACKS[] = {\n"
    tracks += "".join(f"    {{{symbol}_DATA, {symbol}_TITLE}},\n" for _, symbol, _ in songs)
    tracks += "};\n"

    output_dir.mkdir(parents=True, exist_ok=True)
    write_if_changed(output_dir / "music_ids.h", catalog)
    write_if_changed(output_dir / "music_tracks.h", tracks)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source-dir", type=Path, required=True)
    parser.add_argument("--output-dir", type=Path, required=True)
    args = parser.parse_args()
    generate(args.source_dir, args.output_dir)
